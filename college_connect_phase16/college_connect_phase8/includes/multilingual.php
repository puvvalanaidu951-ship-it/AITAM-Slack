function cc_multilingual_languages(): array
{
    return [
        'en' => 'English',
        'te' => 'తెలుగు',
        'hi' => 'हिन्दी',
        'ta' => 'தமிழ்',
        'kn' => 'ಕನ್ನಡ',
        'or' => 'ଓଡ଼ିଆ',
    ];
}

function cc_multilingual_normalize_language($language, string $fallback = 'en'): string
{
    $languages = cc_multilingual_languages();
    $fallback = isset($languages[$fallback]) ? $fallback : 'en';

    return is_string($language) && isset($languages[$language])
        ? $language
        : $fallback;
}

function cc_multilingual_detect_language(string $text): string
{
    if (!mb_check_encoding($text, 'UTF-8')) {
        return 'en';
    }

    $patterns = [
        'te' => '/[\x{0C00}-\x{0C7F}]/u',
        'hi' => '/[\x{0900}-\x{097F}]/u',
        'ta' => '/[\x{0B80}-\x{0BFF}]/u',
        'kn' => '/[\x{0C80}-\x{0CFF}]/u',
        'or' => '/[\x{0B00}-\x{0B7F}]/u',
    ];
    $counts = array_fill_keys(array_keys($patterns), 0);

    foreach ($patterns as $language => $pattern) {
        $count = preg_match_all($pattern, $text);
        $counts[$language] = $count === false ? 0 : $count;
    }

    arsort($counts);
    $language = (string) array_key_first($counts);

    return $counts[$language] > 0 ? $language : 'en';
}

function cc_multilingual_effective_language(array $record, string $text): string
{
    $storedLanguage = cc_multilingual_normalize_language(
        $record['language_code'] ?? null
    );

    return $storedLanguage === 'en'
        ? cc_multilingual_detect_language($text)
        : $storedLanguage;
}

function cc_multilingual_current_interface_language(): string
{
    return cc_multilingual_normalize_language(
        $_SESSION['cc_interface_language'] ?? 'en'
    );
}

